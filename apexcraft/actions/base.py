"""Adapter contract: one bounded step per tick, no background work after cancel."""
from typing import Protocol
from apexcraft.runtime.cancellation import CancellationToken
from apexcraft.world.model import WorldSnapshot


class Action(Protocol):
    def start(self, token: CancellationToken) -> None: ...
    def tick(self, world: WorldSnapshot) -> None: ...
    def is_complete(self) -> bool: ...
    def verify(self, world: WorldSnapshot) -> bool: ...
    def cancel(self) -> None:
        """Idempotently stop interactions and release all held inputs immediately."""
        ...
